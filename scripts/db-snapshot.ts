/*
 * Read-only snapshot of the live database's structure.
 *
 *   npm run db:snapshot
 *
 * Writes supabase/snapshot/live-schema.md: tables and columns, indexes,
 * RLS policies, functions (with who may run them), triggers, event
 * triggers and table grants for the public schema, plus storage
 * policies. Committing it lets changes made outside the migrations
 * (e.g. in the dashboard) show up in a git diff. Contains no row data.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { projectPath, run } from "./lib/db";

const out = projectPath("supabase/snapshot/live-schema.md");

run(async (client) => {
  const q = async <T extends object>(sql: string) => (await client.query<T>(sql)).rows;
  const lines: string[] = [
    "# Live schema snapshot",
    "",
    "Generated by `npm run db:snapshot`. Do not edit by hand. Compare with `supabase/migrations/`.",
    "",
  ];
  const section = (title: string) => lines.push("", `## ${title}`, "");

  const applied = await q<{ name: string }>("select name from phonelab_private.applied_migrations order by name");
  section("Applied migrations (phonelab_private.applied_migrations)");
  for (const r of applied) lines.push(`- ${r.name}`);

  const columns = await q<{ table_name: string; column_name: string; data_type: string; is_nullable: string; column_default: string | null }>(`
    select table_name, column_name, data_type, is_nullable, column_default
    from information_schema.columns where table_schema = 'public'
    order by table_name, ordinal_position`);
  section("Tables and columns");
  let current = "";
  for (const c of columns) {
    if (c.table_name !== current) {
      current = c.table_name;
      lines.push("", `### ${current}`);
    }
    lines.push(`- ${c.column_name}: ${c.data_type}${c.is_nullable === "NO" ? " not null" : ""}${c.column_default ? ` default ${c.column_default}` : ""}`);
  }

  const indexes = await q<{ indexdef: string }>("select indexdef from pg_indexes where schemaname = 'public' order by tablename, indexname");
  section("Indexes");
  lines.push("```sql", ...indexes.map((i) => `${i.indexdef};`), "```");

  const policies = await q<{ schemaname: string; tablename: string; policyname: string; cmd: string; roles: string; qual: string | null; with_check: string | null }>(`
    select schemaname, tablename, policyname, cmd, roles::text, qual, with_check from pg_policies
    where schemaname = 'public' or (schemaname = 'storage' and tablename = 'objects')
    order by schemaname, tablename, policyname`);
  section("RLS policies");
  for (const p of policies) {
    lines.push(`- **${p.schemaname}.${p.tablename}**: "${p.policyname}" ${p.cmd} to ${p.roles}`);
    if (p.qual) lines.push(`  - using: \`${p.qual}\``);
    if (p.with_check) lines.push(`  - with check: \`${p.with_check}\``);
  }

  const functions = await q<{ name: string; owner: string; definer: boolean; acl: string | null; def: string }>(`
    select p.proname as name, pg_get_userbyid(p.proowner) as owner, p.prosecdef as definer,
           p.proacl::text as acl, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' order by p.proname`);
  section("Functions");
  for (const f of functions) {
    lines.push(`### ${f.name}`, "", `Owner ${f.owner}, ${f.definer ? "SECURITY DEFINER" : "SECURITY INVOKER"}, execute grants: \`${f.acl ?? "default (PUBLIC)"}\``, "", "```sql", f.def.trim(), "```", "");
  }

  const triggers = await q<{ table_name: string; tgname: string; def: string }>(`
    select c.relname as table_name, t.tgname, pg_get_triggerdef(t.oid) as def from pg_trigger t
    join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
    where not t.tgisinternal and (n.nspname = 'public' or (n.nspname = 'auth' and c.relname = 'users'))
    order by c.relname, t.tgname`);
  section("Triggers");
  lines.push("```sql", ...triggers.map((t) => `${t.def};`), "```");

  const eventTriggers = await q<{ evtname: string; evtevent: string; fn: string; enabled: string }>(`
    select evtname, evtevent, evtfoid::regproc::text as fn, evtenabled as enabled from pg_event_trigger order by evtname`);
  section("Event triggers");
  for (const e of eventTriggers) lines.push(`- ${e.evtname}: on ${e.evtevent} runs ${e.fn} (enabled: ${e.enabled})`);

  const grants = await q<{ grantee: string; table_name: string; privileges: string }>(`
    select grantee, table_name, string_agg(privilege_type, ', ' order by privilege_type) as privileges
    from information_schema.role_table_grants
    where table_schema = 'public' and grantee in ('anon', 'authenticated')
    group by grantee, table_name order by table_name, grantee`);
  section("Table grants to browser roles");
  for (const g of grants) lines.push(`- ${g.table_name} → ${g.grantee}: ${g.privileges}`);

  mkdirSync(projectPath("supabase/snapshot/"), { recursive: true });
  writeFileSync(out, `${lines.join("\n")}\n`);
  console.log(`Wrote ${out}: ${columns.length} columns, ${policies.length} policies, ${functions.length} functions.`);
});
