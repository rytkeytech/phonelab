/*
 * Generates supabase/seed.sql from the content in src/data.
 * The code stays the source of truth; re-run after editing lessons or scenarios:
 *
 *   npm run db:seed-sql
 *
 * Sample repair cases are deliberately NOT seeded: they are fictional.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { courses, lessons } from "../src/data/learning";
import { scenarios } from "../src/data/diagnose";
import { faultCategories } from "../src/data/repairs/taxonomy";

const text = (value: string | null | undefined) =>
  value == null ? "null" : `'${value.replace(/'/g, "''")}'`;
const textArray = (values: string[]) =>
  values.length ? `array[${values.map(text).join(", ")}]::text[]` : "'{}'::text[]";
const json = (value: unknown) => `${text(JSON.stringify(value))}::jsonb`;

function upsert(table: string, columns: string[], rows: string[][], conflict: string) {
  if (rows.length === 0) return "";
  const updates = columns.filter((c) => !conflict.split(",").map((s) => s.trim()).includes(c));
  return [
    `insert into public.${table} (${columns.join(", ")}) values`,
    rows.map((r) => `  (${r.join(", ")})`).join(",\n"),
    `on conflict (${conflict}) do update set ${updates.map((c) => `${c} = excluded.${c}`).join(", ")};`,
    "",
  ].join("\n");
}

const sql = [
  "-- GENERATED by scripts/generate-seed.ts. Do not edit by hand.",
  "-- Loads learning content, quizzes, game scenarios and fault categories.",
  "-- Safe to re-run: existing rows are updated.",
  "",
  "begin;",
  "",
  upsert(
    "fault_categories",
    ["id", "label", "sort_order"],
    faultCategories.map((c, i) => [text(c.id), text(c.label), String(i)]),
    "id",
  ),
  upsert(
    "courses",
    ["id", "sort_order", "title", "description"],
    courses.map((c) => [text(c.id), String(c.order), text(c.title), text(c.description)]),
    "id",
  ),
  upsert(
    "lessons",
    ["id", "course_id", "slug", "sort_order", "title", "summary", "minutes", "difficulty", "status", "objectives", "blocks"],
    lessons.map((l) => [
      text(l.id), text(l.courseId), text(l.slug), String(l.order), text(l.title), text(l.summary),
      String(l.minutes), text(l.difficulty), text(l.status), textArray(l.objectives), json(l.blocks),
    ]),
    "id",
  ),
  // Planned lessons have no page or progress, so renamed ones are simply dropped.
  `delete from public.lessons where status = 'planned' and id not in (${lessons.map((l) => text(l.id)).join(", ")});`,
  "",
  upsert(
    "quizzes",
    ["lesson_id", "questions"],
    lessons.filter((l) => l.quiz.length > 0).map((l) => [text(l.id), json(l.quiz)]),
    "lesson_id",
  ),
  upsert(
    "game_scenarios",
    ["id", "title", "symptom", "difficulty", "brief", "device", "debrief", "related_lesson_ids", "related_blocks"],
    scenarios.map((s) => [
      text(s.id), text(s.title), text(s.symptom), text(s.difficulty), text(s.brief), text(s.device),
      json(s.debrief), textArray(s.relatedLessonIds), textArray(s.relatedBlocks),
    ]),
    "id",
  ),
  // Steps are replaced wholesale so removed or reordered steps don't linger.
  `delete from public.game_steps where scenario_id in (${scenarios.map((s) => text(s.id)).join(", ")});`,
  upsert(
    "game_steps",
    ["scenario_id", "position", "step_key", "prompt", "choices"],
    scenarios.flatMap((s) => s.steps.map((step, i) => [text(s.id), String(i), text(step.id), text(step.prompt), json(step.choices)])),
    "scenario_id, position",
  ),
  "commit;",
  "",
].join("\n");

const out = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
writeFileSync(out, sql);
console.log(`Wrote ${out}: ${courses.length} courses, ${lessons.length} lessons, ${scenarios.length} scenarios.`);
